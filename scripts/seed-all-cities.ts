async function main() {
  console.log(`Total cities in data: ${ALL_CITIES.length}`);

  const existing: { id: number; slug: string }[] = await get('city?select=id,slug');
  const existingSlugs = new Set(existing.map((c) => c.slug));
  console.log(`Existing cities in DB: ${existing.length}`);

  let added = 0;
  let skipped = 0;
  let failed = 0;

  for (const [name, slug, lat, lng] of ALL_CITIES) {
    if (existingSlugs.has(slug)) {
      skipped++;
      continue;
    }

    const result = await post('city', {
      name,
      slug,
      lat,
      lng,
      is_active: true,
    });

    if (result) {
      added++;
      if (added % 50 === 0) console.log(`  Progress: ${added} added...`);
    } else {
      failed++;
      console.error(`  FAILED: ${name} (${slug})`);
    }
  }

  console.log(`\nDone! Added: ${added}, Skipped: ${skipped}, Failed: ${failed}`);
  console.log(`Total cities in DB: ${existing.length + added}`);
}

main().catch(console.error);
